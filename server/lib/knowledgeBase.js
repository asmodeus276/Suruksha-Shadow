/**
 * High-speed, zero-network in-memory matcher for legal and safety queries.
 * Ranks documents using exact section hits, domain keywords, and bilingual intent tags.
 * Runs in < 0.5 milliseconds.
 */
export function fastMatchDocuments(query, maxResults = 3) {
  if (!query || typeof query !== "string") return [];
  const q = query.toLowerCase().trim();

  // Extract explicit section numbers (e.g. 78, 75, 74, 112, 173, etc.)
  const sectionNums = q.match(/\b\d+\b/g) || [];

  // Split tokens (min 3 chars)
  const tokens = q.split(/[\s,?.!/\\-]+/).filter((t) => t.length >= 3);

  const scored = DOCUMENTS.map((doc) => {
    let score = 0;
    const titleLower = doc.title.toLowerCase();
    const contentLower = doc.content.toLowerCase();

    // 1. Direct section number match (highest confidence)
    for (const num of sectionNums) {
      if (titleLower.includes(`section ${num}`) || titleLower.includes(` ${num} `) || titleLower.includes(`${num} —`)) {
        score += 60;
      } else if (contentLower.includes(`section ${num}`) || contentLower.includes(`${num}`)) {
        score += 25;
      }
    }

    // 2. Token overlap
    for (const token of tokens) {
      if (titleLower.includes(token)) score += 12;
      else if (contentLower.includes(token)) score += 3;
    }

    // 3. Domain Intent & Bilingual Keyword Boosts
    // Stalking / Following
    if ((q.includes("stalk") || q.includes("follow") || q.includes("picha") || q.includes("peechha")) && titleLower.includes("stalking")) score += 40;
    // Harassment / Modesty
    if ((q.includes("harass") || q.includes("chhed") || q.includes("ched") || q.includes("comment") || q.includes("touch")) && (titleLower.includes("harassment") || titleLower.includes("modesty"))) score += 35;
    // FIR / Police / Station
    if ((q.includes("fir") || q.includes("police") || q.includes("thana") || q.includes("report")) && titleLower.includes("fir")) score += 40;
    // Arrest / Night / Time
    if ((q.includes("arrest") || q.includes("night") || q.includes("raat") || q.includes("sunset") || q.includes("girftar")) && titleLower.includes("arrest")) score += 40;
    // Workplace / POSH / Office / Boss
    if ((q.includes("office") || q.includes("work") || q.includes("posh") || q.includes("boss") || q.includes("colleague")) && doc.source === "POSH") score += 35;
    // Domestic Violence / Dowry / Marriage / In-laws
    if ((q.includes("husband") || q.includes("pati") || q.includes("dahej") || q.includes("dowry") || q.includes("sasural") || q.includes("in-law") || q.includes("cruelty")) && (titleLower.includes("cruelty") || titleLower.includes("dowry"))) score += 40;
    // False promise of marriage
    if ((q.includes("shadi") || q.includes("marriage") || q.includes("promise") || q.includes("deceit")) && titleLower.includes("deceitful")) score += 40;
    // Acid attack
    if ((q.includes("acid") || q.includes("tezaab") || q.includes("corrosive")) && titleLower.includes("acid")) score += 50;
    // Cyber / Leak / Photo / Video / MMS / Internet
    if ((q.includes("cyber") || q.includes("online") || q.includes("photo") || q.includes("video") || q.includes("leak") || q.includes("mms") || q.includes("whatsapp")) && (titleLower.includes("voyeurism") || titleLower.includes("cyber") || titleLower.includes("it act"))) score += 40;
    // Evidence / Recording / Proof
    if ((q.includes("evidence") || q.includes("proof") || q.includes("saboot") || q.includes("recording") || q.includes("audio")) && titleLower.includes("electronic")) score += 40;
    // Medical / Hospital
    if ((q.includes("hospital") || q.includes("doctor") || q.includes("medical") || q.includes("treatment")) && titleLower.includes("medical")) score += 45;
    // Minor / Child / School
    if ((q.includes("child") || q.includes("bacha") || q.includes("minor") || q.includes("pocso")) && doc.source === "POCSO") score += 50;

    return { doc, score };
  });

  return scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxResults)
    .map((item) => item.doc);
}
